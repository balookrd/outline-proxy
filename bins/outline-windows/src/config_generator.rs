use crate::profile_store::ServerProfile;

/// Generates TOML configuration files for running `outline-ws-rust.exe`.
pub struct ConfigGenerator;

impl ConfigGenerator {
    /// Generates a complete TOML configuration string for `outline-ws-rust`.
    ///
    /// - `profile`: Target server profile.
    /// - `tcp_only`: Force TCP-only mode (downgrade h3 transports to h2 and strip h3 from ALPN).
    /// - `socks_port`: Port for local SOCKS5 inbound listener.
    /// - `tun_enabled`: Whether TUN mode (Wintun device) should be enabled.
    pub fn generate(
        profile: &ServerProfile,
        tcp_only: bool,
        socks_port: u16,
        tun_enabled: bool,
    ) -> String {
        let effective_tcp_only = tcp_only || profile.tcp_only;

        // Subscriptions return their cached TOML directly if available
        if profile.is_subscription() && !profile.cached_toml.trim().is_empty() {
            let config = apply_mode_configuration(&profile.cached_toml, tun_enabled, socks_port);
            return if effective_tcp_only {
                TcpOnlyConfig::apply(&config)
            } else {
                config
            };
        }

        // Raw override escape hatch
        if !profile.raw_toml_override.trim().is_empty() {
            let config =
                apply_mode_configuration(&profile.raw_toml_override, tun_enabled, socks_port);
            return if effective_tcp_only {
                TcpOnlyConfig::apply(&config)
            } else {
                config
            };
        }

        let link_str = if effective_tcp_only {
            TcpOnlyConfig::enforce_link(&profile.link)
        } else {
            profile.link.clone()
        };

        let transport_str = if effective_tcp_only {
            match profile.transport.as_str() {
                "xhttp_h3" => "xhttp_h2",
                "ws_h3" => "ws_h2",
                other => other,
            }
        } else {
            profile.transport.as_str()
        };

        let uplink_name = if profile.name.trim().is_empty() {
            "primary"
        } else {
            profile.name.trim()
        };

        let mut toml = String::new();
        toml.push_str("# Generated by Outline Proxy for Windows\n");
        toml.push_str("[socks5]\n");
        toml.push_str(&format!("listen = \"127.0.0.1:{socks_port}\"\n\n"));

        if tun_enabled {
            toml.push_str("[tun]\n");
            toml.push_str("name = \"OutlineProxy\"\n");
            toml.push_str("mtu = 1500\n");
            toml.push_str("sniff_quic = true\n\n");
            toml.push_str("[tun.tcp]\n");
            toml.push_str("sniffing = true\n\n");
        }

        toml.push_str("[h2]\n");
        toml.push_str("keepalive_interval_secs = 60\n");
        toml.push_str("keepalive_timeout_secs = 20\n\n");

        toml.push_str("[quic]\n");
        toml.push_str("keepalive_secs = 25\n\n");

        toml.push_str("[[outline.uplinks]]\n");
        toml.push_str(&format!("name = \"{}\"\n", escape_toml(uplink_name)));
        toml.push_str(&format!("transport = \"{}\"\n", escape_toml(transport_str)));
        toml.push_str(&format!("link = \"{}\"\n\n", escape_toml(&link_str)));

        toml.push_str("[padding]\n");
        toml.push_str(&format!("enabled = {}\n", profile.padding_enabled));

        if effective_tcp_only {
            TcpOnlyConfig::apply(&toml)
        } else {
            toml
        }
    }
}

/// Applies mode adjustments (SOCKS5 vs TUN, port, Wintun adapter name) to an existing TOML config.
fn apply_mode_configuration(toml: &str, tun_enabled: bool, socks_port: u16) -> String {
    let lines = toml.lines();

    if !tun_enabled {
        // Strip any [tun] and [tun.*] sections completely so it doesn't attempt to open Wintun without admin privileges
        let mut filtered = Vec::new();
        let mut in_tun_section = false;

        for line in lines {
            let trimmed = line.trim();
            if trimmed.starts_with("[tun") {
                in_tun_section = true;
                continue;
            } else if trimmed.starts_with('[') && !trimmed.starts_with("[tun") {
                in_tun_section = false;
            }

            if !in_tun_section {
                filtered.push(line);
            }
        }

        let mut result = filtered.join("\n");
        if !result.contains("[socks5]") {
            result = format!("[socks5]\nlisten = \"127.0.0.1:{socks_port}\"\n\n{result}");
        }
        result
    } else {
        // TUN mode: ensure [tun] exists with name = "OutlineProxy", replacing any path = "utun" or path = "vpn"
        let mut modified = Vec::new();
        for line in lines {
            let trimmed = line.trim();
            if trimmed.starts_with("path =")
                && (trimmed.contains("\"utun\"")
                    || trimmed.contains("'utun'")
                    || trimmed.contains("\"vpn\"")
                    || trimmed.contains("'vpn'"))
            {
                modified.push("name = \"OutlineProxy\"");
            } else {
                modified.push(line);
            }
        }

        let mut result = modified.join("\n");
        if !result.contains("[tun]") {
            result.push_str(
                "\n\n[tun]\nname = \"OutlineProxy\"\nmtu = 1500\nsniff_quic = true\n\n[tun.tcp]\nsniffing = true\n",
            );
        }
        if !result.contains("[socks5]") {
            result = format!("[socks5]\nlisten = \"127.0.0.1:{socks_port}\"\n\n{result}");
        }
        result
    }
}

/// Utility for rewriting h3 carrier transports and query parameters to enforce TCP-only connections.
pub struct TcpOnlyConfig;

impl TcpOnlyConfig {
    /// Rewrites h3 carrier transports (`xhttp_h3` -> `xhttp_h2`, `ws_h3` -> `ws_h2`)
    /// and strips `h3` from ALPN parameters in links embedded within TOML.
    pub fn apply(raw_toml: &str) -> String {
        let mut result = String::with_capacity(raw_toml.len());

        for line in raw_toml.lines() {
            let trimmed = line.trim();

            // 1. Rewrite carrier transports
            if is_h3_transport_line(trimmed) {
                let replaced = replace_h3_transport(line);
                result.push_str(&replaced);
                result.push('\n');
                continue;
            }

            // 2. Rewrite links containing alpn
            if is_link_line(trimmed) {
                let replaced = replace_link_line(line);
                result.push_str(&replaced);
                result.push('\n');
                continue;
            }

            result.push_str(line);
            result.push('\n');
        }

        // Preserve trailing newline behavior matching original
        if !raw_toml.ends_with('\n') && result.ends_with('\n') {
            result.pop();
        }

        result
    }

    /// Rewrites `alpn=...` in a link string so that `h3` is eliminated.
    /// If no ALPN tokens remain after stripping `h3`, defaults to `h2`.
    pub fn enforce_link(link: &str) -> String {
        let mut result = link.to_string();

        let search_patterns = ["?alpn=", "&alpn="];
        for pattern in &search_patterns {
            let mut search_from = 0;
            while let Some(idx) = result[search_from..].find(pattern) {
                let abs_idx = search_from + idx;
                let val_start = abs_idx + pattern.len();
                let val_end = result[val_start..]
                    .find(&['&', '#', '"', '\'', ' '][..])
                    .map(|end| val_start + end)
                    .unwrap_or(result.len());

                let raw_alpn = &result[val_start..val_end];
                let tokens: Vec<&str> =
                    raw_alpn.split(',').map(str::trim).filter(|t| !t.is_empty()).collect();

                let clean: Vec<&str> =
                    tokens.into_iter().filter(|t| !t.eq_ignore_ascii_case("h3")).collect();

                let new_alpn = if clean.is_empty() {
                    "h2".to_string()
                } else {
                    clean.join(",")
                };

                result.replace_range(val_start..val_end, &new_alpn);
                search_from = val_start + new_alpn.len();
            }
        }

        result
    }
}

fn is_h3_transport_line(trimmed: &str) -> bool {
    let prefixes = [
        "transport =",
        "transport=",
        "vless_mode =",
        "vless_mode=",
        "ss_mode =",
        "ss_mode=",
        "tcp_mode =",
        "tcp_mode=",
        "udp_mode =",
        "udp_mode=",
    ];

    prefixes.iter().any(|prefix| trimmed.starts_with(prefix))
        && (trimmed.contains("xhttp_h3") || trimmed.contains("ws_h3"))
}

fn replace_h3_transport(line: &str) -> String {
    line.replace("xhttp_h3", "xhttp_h2").replace("ws_h3", "ws_h2")
}

fn is_link_line(trimmed: &str) -> bool {
    (trimmed.starts_with("link =") || trimmed.starts_with("link=")) && trimmed.contains("alpn=")
}

fn replace_link_line(line: &str) -> String {
    // Extract quotes around link
    if let Some(first_quote) = line.find(&['"', '\''][..]) {
        let quote_char = line.chars().nth(first_quote).unwrap();
        if let Some(last_quote) = line[first_quote + 1..].rfind(quote_char) {
            let abs_last = first_quote + 1 + last_quote;
            let link = &line[first_quote + 1..abs_last];
            let sanitized = TcpOnlyConfig::enforce_link(link);
            return format!(
                "{}{}{}{}",
                &line[..=first_quote],
                sanitized,
                quote_char,
                &line[abs_last + 1..]
            );
        }
    }
    line.to_string()
}

fn escape_toml(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}
